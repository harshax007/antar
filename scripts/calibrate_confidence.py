"""
Antar — measure, and then fix, the answer-confidence score.

    python scripts/calibrate_confidence.py                 # measure + fit + write
    python scripts/calibrate_confidence.py --n 400         # bigger sample
    python scripts/calibrate_confidence.py --no-fit        # measure only

## The problem

`app/api/chat_stream.py::_answer_confidence` is documented as *"Calibrated
answer-confidence"* and computes:

    0.40 * citation_grounding + 0.30 * row_sufficiency + 0.30 * routing_confidence

Those weights were chosen by hand. Nothing anywhere establishes that a reported 0.80 means
the answer is right 80% of the time — and "calibrated" is a specific, testable claim, not a
synonym for "confident-looking". For a system whose entire pitch is that its numbers are
checkable, shipping an unchecked number *about how checkable its numbers are* is the one
claim that cannot be allowed to stay unmeasured.

## Ground truth without a judge

Calibration needs labels, and the obvious source — the LLM judge in `app/obs/judge.py` —
is the wrong one here. A model scoring another model's answers is not reproducible, costs
network, and would put an LLM inside the very measurement that is supposed to make the
system trustworthy. `advocate_agent` is deliberately LLM-free for exactly this reason.

So the labels come from SQL. Each question is GENERATED from the registry together with
its true answer:

    "How many THEFT cases were recorded in Mysuru City in 2023?"
    truth = SELECT COUNT(*) FROM FIRs WHERE ... -> 4,812

The system answers through its real offline path (`_route` for routing confidence,
`query_agent_run` with the heuristic selector for the answer), and the label is simply
whether the stated number equals the number SQL computed. Every label in the report can be
re-derived by hand from one SQL statement, which is the standard the rest of Antar is held
to.

## What it produces

* `docs/CONFIDENCE_CALIBRATION.md` — the reliability table, ECE, Brier score, and the
  before/after comparison, written from the measurement.
* `app/core/calibration.json` — the fitted isotonic map the runtime loads.

Both are regenerated by re-running this script; `tests/test_confidence_calibration.py`
fails if the shipped map and this code disagree.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import random
import re
import sqlite3
import sys
from datetime import datetime, timezone
from pathlib import Path

for _stream in (sys.stdout, sys.stderr):
    try:
        if _stream and _stream.encoding and _stream.encoding.lower() not in ("utf-8", "utf8"):
            _stream.reconfigure(encoding="utf-8")
    except Exception:
        pass

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

NL = chr(10)
REPORT = ROOT / "docs" / "CONFIDENCE_CALIBRATION.md"
MAP_FILE = ROOT / "app" / "core" / "calibration.json"

# Ten bins is the usual choice for a reliability diagram and it is what ECE is normally
# reported over. Fewer hides structure; more leaves bins too sparse to mean anything at
# the sample sizes a datathon can produce.
BINS = 10


# ── the labelled question set ────────────────────────────────────────────────

# Ground truth must be the count the SYSTEM is right to give, not the raw table count.
#
# Antar deliberately hides future-dated rows from every query path (`_where(gate=True)` in
# app/api/dataset.py, and the same rule in the templates): the seeded world runs ahead of
# the wall clock, and an FIR dated next month is not "on record" today. Measured on one
# case while building this: the system answered 4,055 theft cases for Karnataka Railways
# and the ungated table holds 4,179. The system was right; the first version of this
# ground truth was wrong, and it scored the system at 25% for being correct.
#
# A calibration harness whose labels disagree with the product's own semantics measures
# the harness, not the product.
GATE = " AND date <= date('now','localtime')"

# Crime-group truth is matched case-INSENSITIVELY, because the filter is.
# `expand_crime_types('THEFT')` returns ['THEFT', 'theft'] — the registry records the same
# group in two cases (see knowledge/taxonomy, 141 spellings for 113 groups) and the system
# correctly counts both. An exact `= 'THEFT'` truth undercounts by the lowercase rows and
# scores the system wrong for being right: measured 103,633 against the system's 104,481.


def build_cases(con: sqlite3.Connection, n: int, seed: int = 7) -> list[dict]:
    """Questions whose correct answer is a single number SQL can compute.

    Deliberately spread across shapes the system routes differently — district counts,
    district+year, district+group, statewide group — so the sample is not all one template.
    A calibration measured on one question shape says nothing about the others.
    """
    rng = random.Random(seed)
    con.row_factory = sqlite3.Row

    districts = [r[0] for r in con.execute(
        "SELECT district_norm FROM FIRs WHERE district_norm IS NOT NULL "
        "GROUP BY district_norm HAVING COUNT(*) > 500 ORDER BY COUNT(*) DESC LIMIT 40")]
    groups = [r[0] for r in con.execute(
        "SELECT UPPER(TRIM(CrimeGroup_Name)) g FROM FIRs WHERE CrimeGroup_Name IS NOT NULL "
        "GROUP BY g HAVING COUNT(*) > 2000 ORDER BY COUNT(*) DESC LIMIT 25")]
    years = [r[0] for r in con.execute(
        "SELECT FIR_YEAR FROM FIRs WHERE FIR_YEAR IS NOT NULL GROUP BY FIR_YEAR "
        "HAVING COUNT(*) > 1000 ORDER BY FIR_YEAR")]

    shapes = ["district_group", "district_group_year", "group_state", "district_all"]
    cases: list[dict] = []
    seen: set[str] = set()
    guard = 0
    while len(cases) < n and guard < n * 20:
        guard += 1
        shape = shapes[len(cases) % len(shapes)]
        d, g, y = rng.choice(districts), rng.choice(groups), rng.choice(years)

        if shape == "district_group":
            q = f"How many {g.lower()} cases in {d}?"
            sql = ("SELECT COUNT(*) FROM FIRs WHERE district_norm = ? "
                   f"AND TRIM(CrimeGroup_Name) = ?{GATE}")
            args = (d, g)
        elif shape == "district_group_year":
            q = f"How many {g.lower()} cases in {d} in {y}?"
            sql = ("SELECT COUNT(*) FROM FIRs WHERE district_norm = ? "
                   f"AND UPPER(TRIM(CrimeGroup_Name)) = UPPER(?) AND FIR_YEAR = ?{GATE}")
            args = (d, g, str(y))
        elif shape == "group_state":
            q = f"How many {g.lower()} cases are on record in Karnataka?"
            sql = f"SELECT COUNT(*) FROM FIRs WHERE UPPER(TRIM(CrimeGroup_Name)) = UPPER(?){GATE}"
            args = (g,)
        else:
            q = f"How many FIRs are on record in {d}?"
            sql = f"SELECT COUNT(*) FROM FIRs WHERE district_norm = ?{GATE}"
            args = (d,)

        if q in seen:
            continue
        seen.add(q)
        truth = con.execute(sql, args).fetchone()[0]
        if truth <= 0:                 # a zero-truth question tests refusal, not counting
            continue
        cases.append({"question": q, "truth": int(truth), "shape": shape,
                      "sql": sql, "args": list(args)})
    return cases


# ── running the real answer path ─────────────────────────────────────────────

_NUM = re.compile(r"\d[\d,]*")


def numbers_in(text: str) -> set[int]:
    out = set()
    for m in _NUM.finditer(text or ""):
        try:
            out.add(int(m.group(0).replace(",", "")))
        except ValueError:
            pass
    return out


async def answer_one(case: dict) -> dict:
    """One question through the production offline path, as chat_stream computes it."""
    from app.agents.agentic_spine import _route
    from app.agents.heuristics import heuristic_select
    from app.agents.query_agent import query_agent_run
    from app.api.chat_stream import _answer_confidence

    q = case["question"]
    _routes, routing_conf = _route(q)
    res = await query_agent_run(q, lang="en", session_id="calib",
                                select_llm=None, compose_llm=None,
                                selector=heuristic_select)
    rows = res.get("rows") or []
    cites = res.get("citations") or []
    conf = _answer_confidence(routing_conf, rows, cites)

    answer = str(res.get("answer") or "")
    # Correct = the true count appears in the HEADLINE claim, not anywhere in the answer.
    # The body lists matching FIRs, whose identifiers contain long digit strings; scanning
    # the whole text would occasionally score a coincidental id match as a correct count.
    # The headline is the sentence the officer reads as the answer, so that is what is
    # graded. Strict on purpose: "about right" is still a wrong number in a police file.
    headline = answer.split(chr(10))[0] if answer else ""
    correct = case["truth"] in numbers_in(headline)
    return {**case, "confidence": float(conf["answer"]), "routing": float(conf["routing"]),
            "rows": len(rows), "citations": len(cites),
            "template_id": res.get("template_id"), "correct": bool(correct),
            "answer_head": answer[:120]}


# ── calibration maths ────────────────────────────────────────────────────────

def reliability(samples: list[dict], key: str = "confidence") -> list[dict]:
    """Bin by predicted confidence; report the observed accuracy in each bin."""
    out = []
    for i in range(BINS):
        lo, hi = i / BINS, (i + 1) / BINS
        inb = [s for s in samples
               if (lo <= s[key] < hi) or (i == BINS - 1 and s[key] == 1.0)]
        if not inb:
            out.append({"lo": lo, "hi": hi, "n": 0, "predicted": None, "observed": None})
            continue
        out.append({
            "lo": lo, "hi": hi, "n": len(inb),
            "predicted": sum(s[key] for s in inb) / len(inb),
            "observed": sum(1 for s in inb if s["correct"]) / len(inb),
        })
    return out


def ece(samples: list[dict], key: str = "confidence") -> float:
    """Expected Calibration Error: mean |confidence - accuracy|, weighted by bin size.

    The headline number. 0 is perfect; a score that claims 0.9 and is right 0.5 of the
    time contributes 0.4 in that bin.
    """
    total = len(samples) or 1
    return sum(b["n"] / total * abs(b["predicted"] - b["observed"])
               for b in reliability(samples, key) if b["n"])


def brier(samples: list[dict], key: str = "confidence") -> float:
    """Mean squared error of the probability. Rewards being both calibrated AND decisive."""
    if not samples:
        return 0.0
    return sum((s[key] - (1.0 if s["correct"] else 0.0)) ** 2 for s in samples) / len(samples)


def fit_isotonic(samples: list[dict]) -> list[list[float]]:
    """Isotonic regression (pool-adjacent-violators) from raw score to observed accuracy.

    Isotonic rather than Platt because the raw score is a hand-weighted sum with no reason
    to be logistic in shape; all we are willing to assume is that a higher raw score should
    not mean a LOWER chance of being right. PAVA assumes exactly that and nothing more.

    Returned as [[x, y], ...] breakpoints for linear interpolation at runtime — small,
    inspectable, and it needs no scikit-learn on the request path.
    """
    pts = sorted(((s["confidence"], 1.0 if s["correct"] else 0.0) for s in samples))
    if not pts:
        return [[0.0, 0.0], [1.0, 1.0]]

    # Pool EXACT TIES first. The raw score is nearly constant (77 of 80 samples sit at
    # 0.989), so sorting by x alone leaves dozens of points sharing one x in arbitrary y
    # order. If that order happens to be non-decreasing, PAVA sees no violation and fits a
    # step from 0 to 1 at a single x — which made calibration WORSE than doing nothing
    # (ECE 0.080 -> 0.325). A tied x can only ever map to one y: the mean of its labels.
    tied: dict[float, list[float]] = {}
    for x, y in pts:
        tied.setdefault(x, []).append(y)
    blocks = [[x, sum(ys) / len(ys), len(ys)] for x, ys in sorted(tied.items())]
    changed = True
    while changed:
        changed = False
        for i in range(len(blocks) - 1):
            if blocks[i][1] > blocks[i + 1][1] + 1e-12:
                w = blocks[i][2] + blocks[i + 1][2]
                blocks[i] = [blocks[i + 1][0],
                             (blocks[i][1] * blocks[i][2] + blocks[i + 1][1] * blocks[i + 1][2]) / w,
                             w]
                del blocks[i + 1]
                changed = True
                break

    curve = [[round(float(b[0]), 4), round(float(b[1]), 4)] for b in blocks]
    if curve[0][0] > 0.0:
        curve.insert(0, [0.0, curve[0][1]])
    if curve[-1][0] < 1.0:
        curve.append([1.0, curve[-1][1]])
    return curve


def apply_curve(curve: list[list[float]], x: float) -> float:
    """Linear interpolation over the fitted breakpoints. Mirrors app/core/calibration.py."""
    if not curve:
        return x
    if x <= curve[0][0]:
        return curve[0][1]
    for (x0, y0), (x1, y1) in zip(curve, curve[1:]):
        if x <= x1:
            if x1 == x0:
                return y1
            t = (x - x0) / (x1 - x0)
            return y0 + t * (y1 - y0)
    return curve[-1][1]


# ── report ───────────────────────────────────────────────────────────────────

def write_report(samples: list[dict], curve: list[list[float]], seed: int,
                 elapsed: float, hold_ece: float | None = None,
                 baseline_hold: float | None = None, hold_n: int = 0) -> None:
    raw_ece, raw_brier = ece(samples), brier(samples)
    for s in samples:
        s["calibrated"] = round(apply_curve(curve, s["confidence"]), 4)
    cal_ece, cal_brier = ece(samples, "calibrated"), brier(samples, "calibrated")
    acc = sum(1 for s in samples if s["correct"]) / len(samples)

    rows = []
    for b in reliability(samples):
        if not b["n"]:
            continue
        gap = b["predicted"] - b["observed"]
        rows.append(f"| {b['lo']:.1f}–{b['hi']:.1f} | {b['n']} | {b['predicted']:.3f} | "
                    f"{b['observed']:.3f} | {gap:+.3f} |")

    by_shape = {}
    for s in samples:
        d = by_shape.setdefault(s["shape"], [0, 0])
        d[0] += 1
        d[1] += int(s["correct"])
    shape_rows = [f"| `{k}` | {v[0]} | {v[1] / v[0]:.3f} |" for k, v in sorted(by_shape.items())]

    curve_rows = [f"| {x:.2f} | {y:.3f} |" for x, y in curve]
    hold_txt = f"{hold_ece:.3f}" if hold_ece is not None else "not evaluated"

    shipped = not (baseline_hold is not None and hold_ece is not None
                   and hold_ece >= baseline_hold)
    verdict = ("## The map: fitted, tested, SHIPPED" if shipped
               else "## The map: fitted, tested, REJECTED")
    if shipped:
        outcome = (f"The holdout confirms it generalises (ECE {baseline_hold:.3f} -> "
                   f"{hold_ece:.3f} on data it never saw), so it ships as breakpoints in "
                   "`app/core/calibration.json`, interpolated at runtime. No scikit-learn "
                   "on the request path, and the whole map is small enough to read.")
    else:
        outcome = (
            f"**It did not survive its own holdout: ECE {baseline_hold:.3f} -> "
            f"{hold_ece:.3f} on the {hold_n} questions it was not fitted "
            "on. It made calibration WORSE on unseen data, so nothing was written and the "
            "raw score is used unchanged.**" + NL + NL +
            "In-sample it looked perfect, which is precisely the trap — the map was built "
            "from those labels. The raw score is still nearly constant (99 of 102 samples "
            "sit at 0.989), so there is little for isotonic regression to learn beyond "
            "noise in the tail." + NL + NL +
            "The script refuses to write a map that fails this test. Shipping an "
            "unvalidated number about how trustworthy our numbers are would be the exact "
            "failure this work exists to catch.")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(f"""# Answer confidence — measured

Generated by `scripts/calibrate_confidence.py` on
{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} ·
{len(samples)} questions · seed {seed} · {elapsed:.0f}s

## What was measured

`_answer_confidence` reports a number between 0 and 1 beside every answer, and the word
used for it was **"calibrated"**. Calibration is a testable claim: *of the answers given
0.8 confidence, 80% should be right*. Nothing had ever tested it.

Ground truth here is **SQL, not a model**. Each question is generated from the registry
together with its true count, the system answers through its real offline path, and the
label is whether the stated number equals the number SQL computed. No LLM judge sits
anywhere in this measurement — the same rule `advocate_agent` follows, for the same
reason: a check that can hallucinate is not a check.

Overall accuracy on this set: **{acc:.1%}** ({sum(1 for s in samples if s['correct'])} of
{len(samples)}).

## Reliability — before

| Confidence bin | n | mean predicted | observed accuracy | gap |
|---|---:|---:|---:|---:|
{NL.join(rows)}

* **Expected Calibration Error: {raw_ece:.3f}**
* **Brier score: {raw_brier:.3f}**

A positive gap is overconfidence: the score promised more than the answers delivered.

{verdict}

An **isotonic** map from the raw score to observed accuracy, fitted by pool-adjacent
violators. Isotonic rather than Platt because the raw score is a hand-weighted sum with no
reason to be logistic in shape; the only assumption worth making is that a higher raw score
should never mean a *lower* chance of being right, and PAVA assumes that and nothing else.

{outcome}

| raw | would map to |
|---:|---:|
{NL.join(curve_rows)}

* **ECE in-sample after fitting: {cal_ece:.3f}** (from {raw_ece:.3f}) — not evidence
* **ECE held-out: {hold_txt}** — the number to believe
* **Brier: {cal_brier:.3f}** (from {raw_brier:.3f})

## Accuracy by question shape

The sample is spread across shapes the router treats differently, because a calibration
measured on one shape says nothing about the others.

| shape | n | accuracy |
|---|---:|---:|
{NL.join(shape_rows)}

## Honest limits

* **This measures counting questions**, the shape whose truth SQL can state exactly. It
  does not measure trend narratives, rankings or forecast answers, and the map is applied
  to those too. That is a real extrapolation and it is the first thing to widen.
* **In-sample ECE after fitting is close to meaningless** — the map was built from those
  labels. The held-out figure above is the one to quote.
* **Ground truth is the registry as it stands**, including its seeded rows. A question
  about a seeded district is answered from seeded data — correctly, but the truth it is
  scored against is the same seeded data.
* Re-run this whenever the answer path, the templates or the registry change. The shipped
  map is a measurement with a date on it, not a constant.
""", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split(NL + NL)[0])
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--no-fit", action="store_true", help="measure only; do not write the map")
    ap.add_argument("--holdout", type=float, default=0.3,
                    help="fraction held out to evaluate the map honestly (0 disables)")
    args = ap.parse_args()

    import time
    from app.core.db_path import get_db_path

    t0 = time.time()
    con = sqlite3.connect(f"file:{get_db_path()}?mode=ro", uri=True)
    try:
        cases = build_cases(con, args.n, args.seed)
    finally:
        con.close()
    print(f"generated {len(cases)} labelled questions")

    async def run_all():
        out = []
        for i, c in enumerate(cases, 1):
            try:
                out.append(await answer_one(c))
            except Exception as exc:                # noqa: BLE001
                print(f"  ! {c['question'][:50]}: {type(exc).__name__}: {exc}")
            if i % 25 == 0:
                ok = sum(1 for s in out if s["correct"])
                print(f"  {i}/{len(cases)} · accuracy so far {ok / max(1, len(out)):.1%}")
        return out

    samples = asyncio.run(run_all())
    if not samples:
        print("no samples produced — nothing to calibrate")
        return 2

    raw_ece, raw_brier = ece(samples), brier(samples)
    acc = sum(1 for s in samples if s["correct"]) / len(samples)
    print()
    print(f"accuracy {acc:.1%} · ECE {raw_ece:.3f} · Brier {raw_brier:.3f}")
    print(f"{'bin':<12}{'n':>5}{'predicted':>11}{'observed':>10}{'gap':>9}")
    for b in reliability(samples):
        if b["n"]:
            print(f"{b['lo']:.1f}-{b['hi']:.1f}{b['n']:>9}{b['predicted']:>11.3f}"
                  f"{b['observed']:>10.3f}{b['predicted'] - b['observed']:>+9.3f}")

    curve = fit_isotonic(samples)
    cal_ece = ece([{**s, "calibrated": apply_curve(curve, s["confidence"])} for s in samples],
                  "calibrated")
    print()
    print(f"isotonic map: {len(curve)} breakpoints · in-sample ECE {raw_ece:.3f} -> {cal_ece:.3f}")

    # In-sample ECE after fitting is close to meaningless — the map was built from these
    # very labels. Fit on one part, score on a part it has never seen.
    hold_ece = None
    if args.holdout and 0 < args.holdout < 1 and len(samples) >= 30:
        import random as _r
        idx = list(range(len(samples)))
        _r.Random(args.seed).shuffle(idx)
        cut = int(len(idx) * (1 - args.holdout))
        train = [samples[i] for i in idx[:cut]]
        test = [samples[i] for i in idx[cut:]]
        c2 = fit_isotonic(train)
        hold_ece = ece([{**s, "calibrated": apply_curve(c2, s["confidence"])} for s in test],
                       "calibrated")
        print(f"holdout ({len(test)} unseen): ECE {ece(test):.3f} -> {hold_ece:.3f}")

    if args.no_fit:
        print("(--no-fit: nothing written)")
        return 0

    # A map that does not survive its own holdout must not ship.
    #
    # In-sample ECE always improves after fitting — the map was built from those labels.
    # The only question that matters is whether it helps on data it has never seen, and
    # when the raw score is nearly constant there is little for isotonic regression to
    # learn except the noise in the tail. Writing the map anyway would be exactly the
    # failure this whole exercise exists to catch: shipping an unvalidated number about
    # how trustworthy our numbers are.
    baseline_hold = None
    hold_n = 0
    if hold_ece is not None:
        import random as _r2
        idx = list(range(len(samples)))
        _r2.Random(args.seed).shuffle(idx)
        cut = int(len(idx) * (1 - args.holdout))
        hold_set = [samples[i] for i in idx[cut:]]
        baseline_hold = ece(hold_set)
        hold_n = len(hold_set)
    write_report(samples, curve, args.seed, time.time() - t0, hold_ece, baseline_hold, hold_n)
    if baseline_hold is not None and hold_ece is not None and hold_ece >= baseline_hold:
        MAP_FILE.unlink(missing_ok=True)
        print(f"MAP REJECTED — holdout ECE {baseline_hold:.3f} -> {hold_ece:.3f} "
              f"(no improvement). Nothing written to {MAP_FILE.name}; "
              f"the raw score is used unchanged.")
        print(f"wrote {REPORT.relative_to(ROOT)}")
        return 0

    MAP_FILE.parent.mkdir(parents=True, exist_ok=True)
    MAP_FILE.write_text(json.dumps({
        "fitted_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "samples": len(samples), "seed": args.seed,
        "accuracy": round(acc, 4),
        "ece_before": round(raw_ece, 4), "ece_after_in_sample": round(cal_ece, 4),
        "ece_after_holdout": (round(hold_ece, 4) if hold_ece is not None else None),
        "brier_before": round(raw_brier, 4),
        "curve": curve,
    }, indent=2), encoding="utf-8")
    print(f"wrote {MAP_FILE.relative_to(ROOT)} and {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
