"""
Security scorecard
==================
Runs the three security suites and writes docs/SECURITY_SCORECARD.md: for each control, how
many hostile cases were tried and how many were stopped.

    python scripts/security_scorecard.py

The suites are pure (no network, no demo database writes), so this is safe to run while the
backend is serving. A case that fails is listed by name. Nothing is rounded: a control with
one failing case is not reported as holding.
"""
from __future__ import annotations

import datetime as dt
import pathlib
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[1]
SUITES = [
    ("tests/test_assume_compromise.py", "Model assumed compromised",
     "The model is not called. Its worst-case output is fed straight into each consumer."),
    ("tests/test_llm_security.py", "Call sites and endpoints",
     "What a browser, a stored turn, a scanned page, a web page or a model reply can put in front of the model or an officer."),
    ("tests/test_rag_security.py", "Core controls",
     "Fencing, the leak marker, ingestion screening, the single choke point, PII redaction."),
    ("tests/test_llm_provider.py", "Any provider",
     "A local or third-party model gets the same hardened request and the same output check."),
]
LABELS = {
    "TestItCannotChooseAQuery": "The model cannot choose a query it was not offered",
    "TestAValueCannotBecomeSql": "A value the model supplies cannot become SQL",
    "TestAnInventedFactDoesNotReachAnOfficer": "An invented number, id or score does not reach an officer",
    "TestWordsCannotAct": "Nothing the model says approves or executes an action",
    "TestCanary": "A leaked system prompt is blocked, however it is spelled",
    "TestOtherLanguages": "Overrides in Kannada and Hindi are detected; FIR prose is not flagged",
    "TestSafeUrl": "Only a plain http(s) link is ever made clickable",
    "TestImageInput": "A scan must be uploaded image data, never an address to fetch",
    "TestScanExtraction": "What is read off a scan is reduced to the fields asked for",
    "TestMapSummary": "The map summary accepts only values the page can produce",
    "TestJudge": "An answer cannot instruct its own rater; scores stay within 0 to 1",
    "TestStoredTurns": "Earlier turns and query rewrites are treated as data",
    "TestOpenWeb": "Open-web text is screened; nothing is invented when a search fails",
    "TestTraceAccess": "The prompt sent to the model is Admin only; the leak marker is never stored",
    "TestRequestBounds": "A question has a size ceiling",
    "TestNormalisation": "Invisible characters, markup and comments are removed before text is read",
    "TestDetection": "Instruction-shaped text is recognised; ordinary FIR prose is not",
    "TestFence": "Outside text is fenced with a tag it cannot forge",
    "TestSystemAndOutput": "The policy travels with every prompt; output is checked",
    "TestIngestionScreen": "A poisoned record is quarantined, not indexed",
    "TestLLMChokePoint": "Every model call passes one protected gateway",
    "TestPII": "Phone, Aadhaar, email and PAN are redacted; case numbers survive",
}


def words(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", " ", name.removeprefix("Test")).capitalize()


def run() -> int:
    out = pathlib.Path(tempfile.mkdtemp()) / "sec.xml"
    cmd = [sys.executable, "-m", "pytest", "--noconftest", "-q", "-p", "no:cacheprovider",
           f"--junitxml={out}", *[s[0] for s in SUITES]]
    proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if not out.exists():
        print(proc.stdout[-2000:], proc.stderr[-2000:])
        return 2

    by_suite: dict[str, dict[str, list]] = {}
    for case in ET.parse(out).getroot().iter("testcase"):
        cls = case.get("classname", "")
        module, _, klass = cls.rpartition(".")
        file = module.replace(".", "/") + ".py"
        if not klass.startswith("Test"):                      # module-level tests
            file, klass = cls.replace(".", "/") + ".py", "(module)"
        bad = case.find("failure") is not None or case.find("error") is not None
        skipped = case.find("skipped") is not None
        by_suite.setdefault(file, {}).setdefault(klass, []).append((case.get("name"), bad, skipped))

    total = stopped = 0
    failing: list[str] = []
    lines = [
        "# Security scorecard",
        "",
        f"Generated by `python scripts/security_scorecard.py` on {dt.date.today().isoformat()}. Do not edit by hand; rerun the script.",
        "",
        "Each row is one control. A case is one hostile input (or, where marked, ordinary text that must not be",
        "flagged). \"Stopped\" means the test that proves the control passed. The suites make no network call and",
        "write nothing to the demo database.",
        "",
    ]
    for file, title, what in SUITES:
        groups = by_suite.get(file, {})
        if not groups:
            lines += [f"## {title}", "", f"No result for `{file}`.", ""]
            continue
        lines += [f"## {title}", "", what, "", "| Control | Cases | Stopped |", "|---|---:|---:|"]
        for klass, cases in groups.items():
            ran = [c for c in cases if not c[2]]
            ok = [c for c in ran if not c[1]]
            total += len(ran)
            stopped += len(ok)
            failing += [f"{file}::{klass}::{c[0]}" for c in ran if c[1]]
            label = LABELS.get(klass) or (words(klass) if klass != "(module)" else "Provider selection and request shape")
            note = f" ({len(cases) - len(ran)} skipped)" if len(ran) != len(cases) else ""
            lines.append(f"| {label} | {len(ran)}{note} | {len(ok)} |")
        lines.append("")

    lines += ["## Total", "", f"**{stopped} of {total} cases stopped.**", ""]
    if failing:
        lines += ["Not stopped:", "", *[f"- `{f}`" for f in failing], ""]
    lines += [
        "## What this does and does not show",
        "",
        "- It shows that each listed control does what it says for the cases written against it.",
        "- It does not show that no other attack exists. The cases were written by the same team that built the controls;",
        "  there has been no external test.",
        "- It does not show that a model will ignore an instruction. The \"assumed compromised\" section is the answer to",
        "  that: with the model fully under an attacker's control, these are the things it still cannot do.",
        "",
    ]
    (ROOT / "docs" / "SECURITY_SCORECARD.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"{stopped} of {total} cases stopped -> docs/SECURITY_SCORECARD.md")
    for f in failing:
        print("NOT STOPPED:", f)
    return 1 if failing else 0


if __name__ == "__main__":
    sys.exit(run())
