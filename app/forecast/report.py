"""docs/FORECAST_BACKTEST.md — written from a back-test result, never by hand."""
from __future__ import annotations

import os

from app.forecast.categories import CATEGORIES
from app.forecast.features import ALL

_HERE = os.path.dirname(os.path.abspath(__file__))
REPORT_PATH = os.path.normpath(os.path.join(_HERE, "..", "..", "docs", "FORECAST_BACKTEST.md"))

LABEL = {ALL: "All crime", **CATEGORIES}


def _p(x: float | None) -> str:
    return "—" if x is None else f"{100 * x:.1f}%"


def _row_capture(cat: str, hd: str, m: dict) -> str:
    c = m["capture"]["top_5pct"]
    pai = m.get("pai", {}).get("top_5pct", {})
    cov = m["coverage"]
    gain = 1 - m["deviance"]["model"] / m["deviance"]["baseline"] if m["deviance"]["baseline"] else 0
    pai_s = (f"{pai['model']['pai']:.1f} ({pai['last4']['pai']:.1f})" if pai else "—")
    return (f"| {LABEL.get(cat, cat)} | {hd} | {m['events']:,} | {_p(c['model'])} | {_p(c['last4'])} "
            f"| {_p(c['last52w'])} | {_p(c['oracle'])} | {c['model_beats_last4_weeks']}/{c['weeks']} "
            f"| {pai_s} | {_p(cov['80']['coverage'])} | {_p(cov['90']['coverage'])} "
            f"| {100 * gain:+.0f}% | {m['mae']['model']:.3f} / {m['mae']['baseline']:.3f} "
            f"| {m['calibration']:.2f} |")


def render(bt: dict) -> str:
    w = bt["window"]
    lines = [
        "# Map forecast — back-test report",
        "",
        f"> Generated by `python -m app.forecast.backtest` on {bt['built_at']} "
        f"(model v{bt['model_version']}, back-test v{bt['version']}, {bt['seconds']} s). "
        "Do not edit by hand — rerun the script.",
        "",
        "## Method",
        "",
        f"- **Data:** the real KSP record only (seeded rows excluded); it ends "
        f"{bt['real_record_ends']}.",
        f"- **Window:** forecasts whose target weeks fall between {w['first_target_week']} and "
        f"the week of {w['last_target_week']} — {w['origins']} weekly origins.",
        f"- **Rolling origin:** refitted every {w['refit_every_weeks']} weeks ({w['refits']} refits), "
        "each on data strictly before its origin; between refits each week is forecast from "
        "the weeks up to it. Nothing is tuned on the scored window.",
        "- **Capture:** share of all crime in the horizon that fell in the top 5% of units "
        "(units with any FIR in the prior 52 weeks), ranked by the forecast — compared with "
        "ranking by the last 4 weeks, by the last 52 weeks, and by what actually happened "
        "(the ceiling).",
        f"- **PAI** (Predictive Accuracy Index, Chainey 2008) = % of crime caught ÷ % of land "
        f"flagged, at 5% of land ({bt['land_km2']:,.0f} km² in the land mask). Beat areas are "
        "Voronoi estimates from their median centroids — the data carries no boundaries — "
        "so PAI is approximate. In brackets: the same for last-4-weeks hotspots.",
        "- **Bands:** share of outcomes inside the 80% and 90% ranges.",
        "- **Deviance gain:** Poisson deviance vs the baseline (seasonal-naive + EWMA); "
        "MAE shown as model / baseline. Calibration = Σ forecast ÷ Σ actual.",
        "",
        "## Headline",
        "",
    ]
    for key, h in bt.get("headline", {}).items():
        ut, cat = key.split(".")
        lines.append(
            f"- **{LABEL.get(cat, cat)}, {ut}s, next 7 days:** the top 5% of {ut}s "
            f"(~{h['top5_units']:,}) caught **{_p(h['top5_caught'])}** of the crime "
            f"(last-4-weeks hotspots: {_p(h['top5_caught_last4'])}; ceiling "
            f"{_p(h['top5_oracle'])}); better than last-4-weeks in "
            f"{h['weeks_model_beats_last4']} of {h['weeks']} weeks."
            + (f" PAI at 5% of land: **{h['pai5']:.1f}** (last-4-weeks {h['pai5_last4']:.1f})."
               if "pai5" in h else "")
            + f" 90% bands held {_p(h['coverage90'])}.")
    for ut in ("beat", "station"):
        res = bt["results"].get(ut)
        if not res:
            continue
        lines += ["", f"## {ut.capitalize()}s", "",
                  "| Category | Days | FIRs | Top 5%: model | last 4 wk | last 52 wk | ceiling "
                  "| Weeks model > last 4 | PAI 5% (last 4) | 80% band | 90% band "
                  "| Deviance gain | MAE model / base | Calib. |",
                  "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for cat in [ALL, *CATEGORIES]:
            for hd in ("7", "28"):
                m = res.get(cat, {}).get(hd)
                if m and "capture" in m:
                    lines.append(_row_capture(cat, hd, m))
    wins = bt.get("station_mae_wins", {})
    if wins:
        lines += ["", "## Per-station error", "",
                  "Stations (with crime in the window) where the model's MAE beat the baseline's.",
                  "", "| Category | Days | Stations | Model better | Tied | Share |", "|---|---|---|---|---|---|"]
        for cat in [ALL, *CATEGORIES]:
            for hd in ("7", "28"):
                s = wins.get(cat, {}).get(hd)
                if s and s["units"]:
                    lines.append(f"| {LABEL.get(cat, cat)} | {hd} | {s['units']:,} | {s['model_better']:,} "
                                 f"| {s['tied']:,} | {_p(s['share_better'])} |")
    lines += ["", "## Coverage by volume (beats, all crime, 7 days)", ""]
    m = bt["results"].get("beat", {}).get(ALL, {}).get("7")
    if m and "coverage" in m:
        lines += ["| Expected FIRs | Rows | 80% band | 90% band |", "|---|---|---|---|"]
        for b, v80 in m["coverage"]["80"]["by_volume"].items():
            v90 = m["coverage"]["90"]["by_volume"].get(b, {})
            lines.append(f"| {b} | {v80['n']:,} | {_p(v80['coverage'])} | {_p(v90.get('coverage'))} |")
    lines += ["", "## Reading this honestly", "",
              "- Forecasts count **reported** FIRs. An area that under-reports looks safe.",
              "- Patrolling where the map points records more FIRs there, which the next forecast "
              "reads as more crime. Rotate some patrols into low-forecast beats.",
              "- The window is one winter (Oct–Mar). Seasonal behaviour in other months is "
              "learned from 2019–2023 but not scored here.",
              "- Categories with too few FIRs fall back to the baseline; their rows above "
              "measure the baseline.", ""]
    return "\n".join(lines)


def write(bt: dict, path: str = REPORT_PATH) -> str:
    from app.core.edition import is_lab
    if is_lab() and path == REPORT_PATH:
        path = os.path.normpath(os.path.join(_HERE, "..", "..", "docs", "lab", "FORECAST_BACKTEST.md"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(bt))
    return path
