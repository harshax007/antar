"""Rolling-origin back-test — Phase 3 of docs/MAP_FORECASTING_PLAN.md.

The credibility layer: every number the product says about its own accuracy comes from
here, is written to forecast_meta ("backtest"), and is regenerated by

    python -m app.forecast.backtest            # all categories, ~5 min on CPU

Method. Real record only (series n_real). Every week whose forecast targets fall inside
Oct 2023 – early Mar 2024 is an origin. The model is refitted every 4 weeks, each time on
data strictly before that origin (its calibration block included); between refits the
latest model forecasts from each new week using only the weeks up to that origin. The
recording level is re-computed at every refit from past weeks only. Nothing is tuned on
the window being scored.

What is scored, per unit type × category × horizon:

  capture   share of the crime in the horizon that fell in the top k% of units, ranked
            by forecast — "the top 5% of beats caught X% of next week's thefts". Units
            = those with any FIR in the 52 weeks before the origin; the denominator is
            ALL the crime, including units outside that set.
  PAI       Predictive Accuracy Index (Chainey 2008): % of crime caught ÷ % of land
            flagged, flagging units in order of forecast density until exactly k% of
            land (the last unit pro rata — beats differ in size, and without that each
            ranking would flag a different amount of land). Beat areas are Voronoi
            estimates (store.py), so PAI here is approximate.
  errors    Poisson deviance and MAE vs the baseline (seasonal-naive + EWMA), EWMA and
            seasonal-naive alone; calibration Σforecast ÷ Σactual.
  coverage  how often the 80% and 90% bands contained the outcome, by volume bin.

Every ranking is compared with the ones an analyst would draw without a model: where
crime was in the last 4 weeks (last4), and where it was over the last 52 (last52w). And with the oracle
(ranking by what actually happened), which is the ceiling.
"""
from __future__ import annotations

import json
import math
import sqlite3
import time
from dataclasses import dataclass
from datetime import date, timedelta

import numpy as np

from app.forecast import asof as asof_mod
from app.forecast import features as F
from app.forecast import model as M
from app.forecast import run as R
from app.core.db_path import registry_connect

WINDOW_FROM = date(2023, 10, 2)          # first target week
REFIT_EVERY = 4                          # weeks
TOP_UNITS = (0.01, 0.05, 0.10)
TOP_AREA = (0.01, 0.05, 0.10)
SCORERS = ("model", "last4", "last52w", "oracle")
META_KEY = "backtest"
VERSION = "2"


@dataclass
class _Rec:
    """One origin's forecasts for one unit type × category × horizon."""
    t: int
    y: np.ndarray
    mu: np.ndarray
    lo80: np.ndarray
    hi80: np.ndarray
    lo90: np.ndarray
    hi90: np.ndarray
    base: dict
    last4: np.ndarray
    usual: np.ndarray
    active: np.ndarray


def _week_index(weeks: list[date], d: date) -> int:
    return (d - weeks[0]).days // 7


def _origins(n_weeks: int, first_target: int, last_target: int, h: int) -> list[int]:
    return [t for t in range(first_target - 1, last_target - h + 1) if t >= 0]


def _rank_top(score: np.ndarray, pool: np.ndarray, k: int) -> np.ndarray:
    """Indices of the k highest-scoring units in `pool`; ties broken by unit order."""
    idx = np.flatnonzero(pool)
    if k <= 0 or not len(idx):
        return idx[:0]
    order = np.lexsort((idx, -score[idx]))
    return idx[order[:k]]


def _area_hit(density: np.ndarray, has_area: np.ndarray, area: np.ndarray, y: np.ndarray,
              budget: float) -> tuple[float, float]:
    """Crime caught, and land flagged, when units are flagged in order of density until
    exactly `budget` km². The last unit counts in proportion to the area it contributes,
    so every ranking flags the same land and ranking by true density is the ceiling."""
    idx = np.flatnonzero(has_area)
    order = idx[np.lexsort((idx, -density[idx]))]
    cum = np.cumsum(area[order])
    j = int(np.searchsorted(cum, budget, side="left"))
    if j >= len(order):
        return float(y[order].sum()), float(cum[-1]) if len(cum) else 0.0
    before = cum[j - 1] if j > 0 else 0.0
    frac = (budget - before) / area[order[j]]
    return float(y[order[:j]].sum() + frac * y[order[j]]), float(budget)


def _scores(r: _Rec, h: int) -> dict[str, np.ndarray]:
    return {"model": r.mu, "last4": r.last4, "last52w": r.usual, "oracle": r.y}


def _metrics(recs: list[_Rec], h: int, area: np.ndarray | None, land: float) -> dict:
    y = np.concatenate([r.y[r.active] for r in recs])
    mu = np.concatenate([r.mu[r.active] for r in recs])
    out: dict = {"origins": len(recs), "events": int(sum(r.y.sum() for r in recs)),
                 "rows": int(len(y))}
    if out["events"] == 0:
        out["note"] = "no crime of this kind in the window"
        return out
    out["calibration"] = round(float(mu.sum() / max(y.sum(), 1e-9)), 3)
    errs = {"model": mu}
    for k in ("baseline", "ewma", "seasonal_naive"):
        errs[k] = np.concatenate([r.base[k][r.active] for r in recs])
    out["deviance"] = {k: round(M.poisson_deviance(y, v), 4) for k, v in errs.items()}
    out["mae"] = {k: round(float(np.mean(np.abs(y - v))), 4) for k, v in errs.items()}

    cov = {}
    bins = M._bin(mu)
    for lv in ("80", "90"):
        lo = np.concatenate([getattr(r, f"lo{lv}")[r.active] for r in recs])
        hi = np.concatenate([getattr(r, f"hi{lv}")[r.active] for r in recs])
        inside = (lo <= y) & (y <= hi)
        by_bin = {}
        for b in range(len(M.BIN_EDGES) + 1):
            m = bins == b
            if m.sum() >= 30:
                by_bin[_bin_label(b)] = {"coverage": round(float(inside[m].mean()), 3),
                                         "n": int(m.sum())}
        cov[lv] = {"coverage": round(float(inside.mean()), 3), "by_volume": by_bin}
    out["coverage"] = cov

    # hotspot capture: top k% of active units by each scorer
    cap: dict = {}
    for k in TOP_UNITS:
        caught = {s: 0.0 for s in SCORERS}
        per_origin = {"model": [], "last4": []}
        total = 0.0
        for r in recs:
            n = max(1, math.ceil(k * r.active.sum()))
            tot = float(r.y.sum())
            total += tot
            for s, score in _scores(r, h).items():
                c = float(r.y[_rank_top(score, r.active, n)].sum())
                caught[s] += c
                if s in per_origin and tot > 0:
                    per_origin[s].append(c / tot)
        cap[_pct(k)] = {
            "units": int(round(np.mean([max(1, math.ceil(k * r.active.sum())) for r in recs]))),
            **{s: round(caught[s] / total, 4) for s in SCORERS},
            "model_beats_last4_weeks": int(sum(a > b for a, b in zip(per_origin["model"], per_origin["last4"]))),
            "weeks": len(per_origin["model"]),
        }
    out["capture"] = cap

    if area is not None and land > 0:
        has = ~np.isnan(area)
        pai: dict = {}
        for k in TOP_AREA:
            budget = k * land
            hits = {s: 0.0 for s in SCORERS}
            shares = {s: [] for s in SCORERS}
            total = 0.0
            for r in recs:
                total += float(r.y.sum())
                for s, score in _scores(r, h).items():
                    dens = np.where(has, score / np.where(has, area, 1.0), 0.0)
                    hit, flagged = _area_hit(dens, has, np.nan_to_num(area), r.y, budget)
                    hits[s] += hit
                    shares[s].append(flagged / land)
            pai[_pct(k)] = {
                s: {"hit": round(hits[s] / total, 4),
                    "area": round(float(np.mean(shares[s])), 4),
                    "pai": round((hits[s] / total) / max(float(np.mean(shares[s])), 1e-9), 2)}
                for s in SCORERS}
        out["pai"] = pai
    return out


def _pct(k: float) -> str:
    return f"top_{int(round(k * 100))}pct"


def _bin_label(b: int) -> str:
    edges = (0,) + M.BIN_EDGES + (math.inf,)
    lo, hi = edges[b], edges[b + 1]
    return f"{lo:g}+" if hi == math.inf else f"{lo:g}-{hi:g}"


def _unit_record(recs: list[_Rec], names: list[str]) -> dict:
    """Per unit, over the window: weeks flagged in the model's top 5%, weeks those flags
    were followed by at least one FIR, and Σ forecast vs Σ actual. Only units flagged at
    least once are kept. This is what a beat card quotes as "this beat's track record"."""
    U = len(names)
    flagged = np.zeros(U, dtype=int)
    hit = np.zeros(U, dtype=int)
    for r in recs:
        top = _rank_top(r.mu, r.active, max(1, math.ceil(0.05 * r.active.sum())))
        flagged[top] += 1
        hit[top] += (r.y[top] > 0).astype(int)
    fc = np.sum([r.mu for r in recs], axis=0)
    ac = np.sum([r.y for r in recs], axis=0)
    return {names[i]: [int(flagged[i]), int(hit[i]), round(float(fc[i]), 1), int(ac[i])]
            for i in np.flatnonzero(flagged)}


def _weekly(recs: list[_Rec], weeks: list[date]) -> list[dict]:
    """The ledger behind the scorecard: for each scored week, what was forecast for the
    7 days ahead and what was then recorded. Totals are over active units, the same scope
    as `calibration`; `caught` is the top-5% capture of `_metrics`, one week at a time."""
    out = []
    for r in recs:
        a = r.active
        row = {"week": weeks[r.t + 1].isoformat(),
               "forecast": round(float(r.mu[a].sum()), 1), "actual": int(round(float(r.y[a].sum()))),
               "in80": round(float(((r.lo80 <= r.y) & (r.y <= r.hi80))[a].mean()), 3)}
        total = float(r.y.sum())
        if total > 0:
            n = max(1, math.ceil(0.05 * a.sum()))
            row["caught"] = round(float(r.y[_rank_top(r.mu, a, n)].sum()) / total, 4)
            row["caught_last4"] = round(float(r.y[_rank_top(r.last4, a, n)].sum()) / total, 4)
        out.append(row)
    return out


def _station_wins(recs: list[_Rec]) -> dict:
    """Share of units where the model's MAE over the window beats the baseline's."""
    Y = np.stack([r.y for r in recs])
    err_m = np.abs(Y - np.stack([r.mu for r in recs])).mean(axis=0)
    err_b = np.abs(Y - np.stack([r.base["baseline"] for r in recs])).mean(axis=0)
    act = np.stack([r.active for r in recs]).any(axis=0) & (Y.sum(axis=0) > 0)
    better = (err_m < err_b)[act]
    tie = (err_m == err_b)[act]
    return {"units": int(act.sum()), "model_better": int(better.sum()),
            "tied": int(tie.sum()), "share_better": round(float(better.mean()), 3) if act.any() else None}


def run(conn: sqlite3.Connection, *, cats: list[str] | None = None,
        unit_types=R.UNIT_TYPES, horizons=tuple(M.HORIZONS), window_from: date = WINDOW_FROM,
        refit_every: int = REFIT_EVERY, log=print) -> dict:
    t_start = time.perf_counter()
    real_end = asof_mod.real_record_end(conn)
    if real_end is None:
        raise ValueError("no real record to back-test on")
    last_sunday = real_end - timedelta(days=(real_end.weekday() + 1) % 7)
    last_target = asof_mod.week_start(last_sunday)
    first_target = asof_mod.week_start(window_from)
    probe = F.calendar(conn, "n_real", last_target)
    weeks = probe.weeks
    ft, lt = _week_index(weeks, first_target), _week_index(weeks, last_target)
    all_origins = sorted({t for h in horizons for t in _origins(len(weeks), ft, lt, M.HORIZONS[h])})
    refits = all_origins[::refit_every]
    cals = {r: F.calendar(conn, "n_real", weeks[r], through=last_target) for r in refits}

    units = {"station": F.load_units(conn, "station")}
    if "beat" in unit_types:
        units["beat"] = F.load_units(conn, "beat")
    area, land = {}, 0.0
    try:
        land = float(conn.execute("SELECT value FROM forecast_meta WHERE key = 'land_km2'").fetchone()[0])
        for ut, u in units.items():
            a = dict(conn.execute("SELECT unit, area_km2 FROM geo_units WHERE unit_type = ?", (ut,)))
            area[ut] = np.array([a.get(n) if a.get(n) is not None else np.nan for n in u.names], dtype=float)
    except (TypeError, sqlite3.OperationalError):
        area = {}

    cats = list(cats or R.categories())
    order = [F.ALL] + [c for c in cats if c != F.ALL]       # ALL first: it defines "active"
    active: dict[str, dict[int, np.ndarray]] = {}
    results: dict = {ut: {} for ut in unit_types}
    station_wins: dict = {}
    for cat in order:
        t0 = time.perf_counter()
        raw = {"station": F.load_panel(conn, units["station"], None, cat, probe)}
        if "beat" in unit_types:
            raw["beat"] = F.load_panel(conn, units["beat"], units["station"], cat, raw["station"].cal)
        if cat == F.ALL:
            for ut in unit_types:
                Yr = raw[ut].Y_raw
                active[ut] = {t: Yr[:, max(0, t - 51): t + 1].sum(axis=1) > 0 for t in all_origins}
        recs = {(ut, h): [] for ut in unit_types for h in horizons}
        for i, r in enumerate(refits):
            nxt = refits[i + 1] if i + 1 < len(refits) else lt + 1
            cal = cals[r]
            ps = F.with_calendar(raw["station"], cal)
            pb = F.with_calendar(raw["beat"], cal) if "beat" in unit_types else None
            for hd in horizons:
                h = M.HORIZONS[hd]
                fs = M.fit(ps, r - h, hd)
                parent = M.Parent(ps, fs)
                fb = M.fit(pb, r - h, hd, parent=parent) if pb is not None else None
                for t in range(r, nxt):
                    if t + h > lt or t < ft - 1:
                        continue
                    for ut, p, f, par in (("station", ps, fs, None), ("beat", pb, fb, parent)):
                        if ut not in unit_types:
                            continue
                        pr = M.predict(p, f, t, par, explain=False)
                        recs[(ut, hd)].append(_Rec(
                            t=t, y=p.target(t, h), mu=pr["expected"], lo80=pr["lo80"],
                            hi80=pr["hi80"], lo90=pr["lo90"], hi90=pr["hi90"],
                            base={k: pr[k] for k in ("baseline", "ewma", "seasonal_naive")},
                            last4=pr["recent4"], usual=pr["usual_level"],
                            active=active[ut][t]))
        if cat not in cats:
            continue
        for (ut, hd), rs in recs.items():
            m = _metrics(rs, M.HORIZONS[hd], area.get(ut), land)
            if hd == 7:
                m["units"] = _unit_record(rs, units[ut].names)
                m["units_fields"] = ["weeks_flagged", "weeks_flagged_with_crime",
                                     "forecast_total", "actual_total"]
                m["weekly"] = _weekly(rs, weeks)
            results[ut].setdefault(cat, {})[str(hd)] = m
            if ut == "station":
                station_wins.setdefault(cat, {})[str(hd)] = _station_wins(rs)
        log(f"  back-test {cat:<10} {time.perf_counter() - t0:5.1f}s")

    out = {
        "version": VERSION, "model_version": R.MODEL_VERSION,
        "series": "n_real", "real_record_ends": real_end.isoformat(),
        "window": {"first_target_week": first_target.isoformat(),
                   "last_target_week": last_target.isoformat(),
                   "origins": len(all_origins), "refits": len(refits),
                   "refit_every_weeks": refit_every},
        "land_km2": land, "results": results, "station_mae_wins": station_wins,
        "seconds": round(time.perf_counter() - t_start, 1),
        "built_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
    }
    out["headline"] = headline(out)
    return out


def headline(bt: dict) -> dict:
    """The few numbers an officer (or a judge) is told."""
    res = bt["results"]
    h: dict = {}
    for ut in ("beat", "station"):
        for cat in (F.ALL, "PROPERTY"):
            m = res.get(ut, {}).get(cat, {}).get("7")
            if not m or "capture" not in m:
                continue
            c5, c10 = m["capture"]["top_5pct"], m["capture"]["top_10pct"]
            item = {
                "top5_units": c5["units"], "top5_caught": c5["model"],
                "top5_caught_last4": c5["last4"], "top5_oracle": c5["oracle"],
                "top10_caught": c10["model"],
                "weeks_model_beats_last4": c5["model_beats_last4_weeks"], "weeks": c5["weeks"],
                "coverage90": m["coverage"]["90"]["coverage"],
                "coverage80": m["coverage"]["80"]["coverage"],
                "deviance_gain": round(1 - m["deviance"]["model"] / m["deviance"]["baseline"], 3),
            }
            if "pai" in m:
                p5 = m["pai"]["top_5pct"]
                item.update({"pai5": p5["model"]["pai"], "pai5_hit": p5["model"]["hit"],
                             "pai5_area": p5["model"]["area"], "pai5_last4": p5["last4"]["pai"],
                             "pai5_oracle": p5["oracle"]["pai"]})
            h[f"{ut}.{cat}"] = item
    return h


def save(conn: sqlite3.Connection, bt: dict) -> None:
    conn.execute("CREATE TABLE IF NOT EXISTS forecast_meta "
                  "(key TEXT PRIMARY KEY, value TEXT) WITHOUT ROWID")
    conn.execute("INSERT OR REPLACE INTO forecast_meta VALUES (?, ?)", (META_KEY, json.dumps(bt)))
    conn.commit()


def load(conn: sqlite3.Connection) -> dict | None:
    try:
        row = conn.execute("SELECT value FROM forecast_meta WHERE key = ?", (META_KEY,)).fetchone()
    except sqlite3.OperationalError:
        return None
    return json.loads(row[0]) if row else None


